package provider

import (
	"context"
	"net/http"

	"github.com/hashicorp/terraform-plugin-framework/datasource"
	"github.com/hashicorp/terraform-plugin-framework/datasource/schema"
	"github.com/hashicorp/terraform-plugin-framework/types"
)

var (
	_ datasource.DataSource                   = &evaluationTaxonomyDataSource{}
	_ datasource.DataSourceWithConfigure      = &evaluationTaxonomyDataSource{}
	_ datasource.DataSourceWithValidateConfig = &evaluationTaxonomyDataSource{}
)

func NewEvaluationTaxonomyDataSource() datasource.DataSource {
	return &evaluationTaxonomyDataSource{}
}

type evaluationTaxonomyDataSource struct {
	previewGate
}

func (d *evaluationTaxonomyDataSource) Metadata(_ context.Context, req datasource.MetadataRequest, resp *datasource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_evaluation_taxonomy"
}

func (d *evaluationTaxonomyDataSource) Schema(_ context.Context, _ datasource.SchemaRequest, resp *datasource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: evaluationsPreviewNoteDataSource + "Looks up a Foundry evaluation taxonomy by name.",
		Attributes: map[string]schema.Attribute{
			"name": schema.StringAttribute{
				Required:            true,
				MarkdownDescription: "Name of the taxonomy.",
			},
			"description": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Description of the taxonomy.",
			},
			"agent_name": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Name of the Foundry agent the taxonomy is generated for.",
			},
			"agent_version": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Version of the Foundry agent the taxonomy is generated for.",
			},
			"risk_categories": schema.ListAttribute{
				Computed:            true,
				ElementType:         types.StringType,
				MarkdownDescription: "Risk categories the taxonomy was generated for.",
			},
			"id": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Service-assigned taxonomy identifier.",
			},
			"version": schema.StringAttribute{
				Computed:            true,
				MarkdownDescription: "Service-assigned taxonomy version.",
			},
			"categories": schema.ListNestedAttribute{
				Computed:            true,
				MarkdownDescription: "Categories generated by the service for the taxonomy, in the order returned by the service.",
				NestedObject: schema.NestedAttributeObject{
					Attributes: map[string]schema.Attribute{
						"id":            schema.StringAttribute{Computed: true, MarkdownDescription: "Service-assigned category identifier."},
						"name":          schema.StringAttribute{Computed: true, MarkdownDescription: "Category name."},
						"description":   schema.StringAttribute{Computed: true, MarkdownDescription: "Category description."},
						"risk_category": schema.StringAttribute{Computed: true, MarkdownDescription: "Risk category this category belongs to."},
						"sub_categories": schema.ListNestedAttribute{
							Computed:            true,
							MarkdownDescription: "Subcategories within this category, in the order returned by the service.",
							NestedObject: schema.NestedAttributeObject{
								Attributes: map[string]schema.Attribute{
									"id":          schema.StringAttribute{Computed: true, MarkdownDescription: "Service-assigned subcategory identifier."},
									"name":        schema.StringAttribute{Computed: true, MarkdownDescription: "Subcategory name."},
									"description": schema.StringAttribute{Computed: true, MarkdownDescription: "Subcategory description."},
									"enabled":     schema.BoolAttribute{Computed: true, MarkdownDescription: "Whether the subcategory is enabled for evaluation."},
								},
							},
						},
					},
				},
			},
		},
	}
}

func (d *evaluationTaxonomyDataSource) ValidateConfig(ctx context.Context, req datasource.ValidateConfigRequest, resp *datasource.ValidateConfigResponse) {
	d.ValidateDataSourceConfig(ctx, req, resp)
}

func (d *evaluationTaxonomyDataSource) Configure(_ context.Context, req datasource.ConfigureRequest, resp *datasource.ConfigureResponse) {
	client := clientFromProviderData(req.ProviderData, &resp.Diagnostics)
	d.previewGate = previewGate{client: client, feature: evaluationsPreviewFeature, name: evaluationsPreviewFeatureName}
}

func (d *evaluationTaxonomyDataSource) Read(ctx context.Context, req datasource.ReadRequest, resp *datasource.ReadResponse) {
	var config evaluationTaxonomyModel
	resp.Diagnostics.Append(req.Config.Get(ctx, &config)...)
	if resp.Diagnostics.HasError() {
		return
	}

	ctx, err := d.previewContext(ctx)
	if err != nil {
		resp.Diagnostics.AddError("Preview feature not enabled", err.Error())
		return
	}

	var response evaluationTaxonomyResponse
	if err := d.client.JSON(ctx, http.MethodGet, config.path(), nil, &response); err != nil {
		resp.Diagnostics.AddError("Unable to read evaluation taxonomy", err.Error())
		return
	}

	config.apply(ctx, response, &resp.Diagnostics)
	resp.Diagnostics.Append(resp.State.Set(ctx, &config)...)
}
